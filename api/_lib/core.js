/** Standard first six ARGV values for a coin script. */
function coinArgs(user, ts) {
  ts = ts || Date.now();
  return [String(ts), weekKey(ts), weekKey(ts - 7 * 864e5), monthKey(ts), user ? user.uid : '', user ? user.th : ''];
}
/** Split a coin script's reply into [main part, {balance, got:[{c, d}]}]. */
function splitCoins(out) {
  const i = out.indexOf('#');
  if (i < 0) return [out, null];
  const rest = out.slice(i + 1);
  const got = [];
  for (let j = 1; j + 1 < rest.length; j += 2) { let d = rest[j + 1]; try { d = JSON.parse(d); } catch (e) { /* keep */ } got.push({ c: Number(rest[j]) || 0, d }); }
  return [out.slice(0, i), { balance: Number(rest[0]) || 0, got, awarded: got.reduce((a, g) => a + g.c, 0) }];
}
